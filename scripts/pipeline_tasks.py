def is_owned_artifact(relative: str | Path) -> bool:
    """Return true only for paths generated by the shared pipeline."""
    rel = Path(relative).as_posix()
    if rel == "index.html" or rel in GENERATED_DOC_PAGES:
        return True
    if rel.startswith("output/") and rel not in {
        "output/attributes.md", "output/individual_position_formulas.txt",
    } and not rel.startswith("output/trained_models/"):
        return True
    if rel == "docs/data/build_manifest.json":
        return True
    if rel.startswith("docs/data/"):
        name = Path(rel).name
        return (
            name in GENERATED_BROWSER_DATA
            or re.fullmatch(r"season\d+_elo\.csv", name) is not None
            or re.fullmatch(r"schedules_season\d+\.json", name) is not None
            or re.fullmatch(r"ranked_sos_by_conference_season\d+\.csv", name) is not None
        )
    return False


def clear_owned_artifacts(root: Path) -> None:
    """Remove known generated paths from a staging copy, preserving all source files."""
    root = Path(root)
    for relative in GENERATED_DOC_PAGES | {"index.html", "docs/data/build_manifest.json"}:
        path = root / relative
        if path.is_file():
            path.unlink()
    data_root = root / "docs" / "data"
    if data_root.is_dir():
        for path in data_root.iterdir():
            if path.is_file() and is_owned_artifact(path.relative_to(root)):
                path.unlink()


