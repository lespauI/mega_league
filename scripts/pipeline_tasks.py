def task_output_paths(task_id: str, display_season: int) -> tuple[str, ...]:
    if task_id == "sos_elo":
        return (
            f"output/sos/season{display_season}_elo.csv",
            f"output/sos/season{display_season}_elo.json",
            f"output/schedules/season{display_season}/all_schedules.json",
        )
    return tuple(path.format(season=display_season) for path in TASK_OUTPUTS.get(task_id, ()))


def task_missing_outputs(workspace: Path, task_id: str, display_season: int) -> list[str]:
    missing = [rel for rel in task_output_paths(task_id, display_season) if not (workspace / rel).is_file()]
    if task_id == "roster_rankings":
        roster_dir = workspace / "output" / "team_rosters"
        main_rosters = []
        if roster_dir.is_dir():
            main_rosters = [path for path in roster_dir.glob("*.csv")
                            if not path.stem.endswith(("_Defense", "_Offense"))]
        if len(main_rosters) < 32:
            missing.append("output/team_rosters/<32 team roster CSVs>")
    return missing


def validate_task_result(result: ScriptResult, workspace: Path, task_id: str, display_season: int) -> ScriptResult:
    """Convert a zero-exit task into failure if its declared outputs are absent."""
    if result.status != ScriptStatus.SUCCEEDED:
        return result
    missing = task_missing_outputs(workspace, task_id, display_season)
    if not missing:
        return result
    return ScriptResult(
        ScriptStatus.FAILED,
        result.description,
        result.returncode,
        error="producer did not create required outputs: " + ", ".join(missing),
    )


def task_regenerates_path(relative: str, task_ids: list[str], display_season: int) -> bool:
    path = Path(relative).as_posix()
    for task_id in task_ids:
        if path in task_output_paths(task_id, display_season):
            return True
        if task_id == "roster_rankings" and path.startswith("output/team_rosters/"):
            return True
    return False


def task_arguments(task_id: str, season_index: int, context: CycleContext) -> list[str]:
    """Build the season and declared-ELO arguments for a task without running it."""
    task = TASKS[task_id]
    arguments = list(task.arguments)
    if task_id in {"sos_elo", "verify_sos_elo", "sos_rankings", "scenarios", "playoff_table", "playoff_html", "week18_simulator"}:
        if task_id == "sos_elo":
            arguments.extend(("--csv-season-index", str(season_index),
                              "--elo-source-week", str(context.elo_source_week)))
        elif task_id == "verify_sos_elo":
            arguments.extend(("--season-index", str(season_index + 1)))
        else:
            arguments.extend(("--season-index", str(season_index)))
    if task_id in {"scenarios", "playoff_table"}:
        arguments.extend(("--elo-source-week", str(context.elo_source_week)))
        arguments.extend(("--seed", str(PIPELINE_SIMULATION_SEED)))
    if task_id == "sos_rankings":
        arguments.extend(("--out-csv", "output/ranked_sos_by_conference.csv"))
    return arguments


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _protected_output_files(root: Path) -> list[Path]:
    output = root / "output"
    files = [output / name for name in PROTECTED_OUTPUT_FILES if (output / name).is_file()]
    models = output / "trained_models"
    if models.is_dir():
        files.extend(path for path in models.rglob("*") if path.is_file())
    return sorted(files)


def _protected_hashes(root: Path) -> dict[str, str]:
    return {path.relative_to(root).as_posix(): _sha256(path) for path in _protected_output_files(root)}


def create_staging_workspace(repository_root: Path) -> tuple[Path, Path, dict[str, str]]:
    """Copy maintained inputs/source and protected assets into a clean build tree."""
    repository_root = Path(repository_root).resolve()
    protected = _protected_hashes(repository_root)
    temporary_root = Path(tempfile.mkdtemp(prefix=".mega-build-", dir=repository_root))
    workspace = temporary_root / "workspace"

    excluded = {
        ".git", "archive", "output", "node_modules", "__pycache__", ".pytest_cache",
        ".zenflow", "test-results", "playwright-report", "playwright/.cache",
    }

    def ignore(directory: str, names: list[str]) -> set[str]:
        ignored = {name for name in names if name in excluded or name.startswith(".mega-build-") or name.startswith(".mega-import-")}
        return ignored

    shutil.copytree(repository_root, workspace, ignore=ignore)
    staged_output = workspace / "output"
    staged_output.mkdir(parents=True, exist_ok=True)
    for relative in protected:
        source = repository_root / relative
        target = workspace / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)

    clear_owned_artifacts(workspace)

    if protected != _protected_hashes(workspace):
        shutil.rmtree(temporary_root, ignore_errors=True)
        raise ValueError("Protected formula/model files changed while creating the staging workspace")
    return temporary_root, workspace, protected


def _read_build_manifest(root: Path) -> dict | None:
    path = root / "output" / "build_manifest.json"
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return value if isinstance(value, dict) else None


def write_build_manifest(
    workspace: Path,
    repository_root: Path,
    group: str,
    context: CycleContext,
    task_ids: list[str],
    *,
    include_index: bool = True,
) -> dict:
    """Write a manifest from owned, staged outputs and verified subset inputs."""
    previous = _read_build_manifest(repository_root)
    if group != "full":
        if not previous or previous.get("complete") is not True:
            raise ValueError("A subset build needs a successful full-build manifest first")
        if previous.get("schemaVersion") != 2:
            raise ValueError("Existing build manifest predates artifact ownership; run a full build before a subset build")
        if previous.get("snapshotId") != context.snapshot_id:
            raise ValueError("A subset build cannot mix artifacts from a different input snapshot; run the full pipeline")

    artifacts: dict[str, str] = {}
    if group != "full" and previous:
        for relative, digest in previous.get("artifacts", {}).items():
            if not is_owned_artifact(relative):
                raise ValueError(f"Previous manifest claims an unowned artifact: {relative}")
            if relative == "index.html" and not include_index:
                continue
            path = workspace / relative
            if path.is_file() and _sha256(path) == digest:
                artifacts[relative] = digest
            elif not task_regenerates_path(relative, task_ids, context.display_season):
                raise ValueError(f"Subset build lost a required same-snapshot artifact: {relative}")

    output_root = workspace / "output"
    for path in output_root.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(workspace).as_posix()
        if relative == "output/build_manifest.json":
            continue
        if relative in _protected_hashes(workspace):
            continue
        if not is_owned_artifact(relative):
            raise ValueError(f"Staged build produced an artifact without an owner: {relative}")
        artifacts[relative] = _sha256(path)

    docs_root = workspace / "docs"
    for path in docs_root.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(workspace).as_posix()
        if relative == "docs/data/build_manifest.json":
            continue
        if is_owned_artifact(relative):
            artifacts[relative] = _sha256(path)
        else:
            source = repository_root / relative
            if not source.is_file() or _sha256(source) != _sha256(path):
                raise ValueError(f"Staged build changed maintained source without an artifact owner: {relative}")

    index_path = workspace / "index.html"
    if include_index and index_path.is_file():
        artifacts["index.html"] = _sha256(index_path)
    else:
        artifacts.pop("index.html", None)

    previous_groups = set(previous.get("groups", [])) if previous and previous.get("snapshotId") == context.snapshot_id else set()
    previous_tasks = set(previous.get("taskIds", [])) if previous and previous.get("snapshotId") == context.snapshot_id else set()
    manifest = {
        "schemaVersion": 2,
        "snapshotId": context.snapshot_id,
        "edition": context.edition,
        "csvSeasonIndex": context.csv_season_index,
        "displaySeason": context.display_season,
        "calendarYear": context.calendar_year,
        "completedThroughWeek": context.completed_through_week,
        "exportWeekIndex": context.export_week_index,
        "eloSourceWeek": context.elo_source_week,
        "pythonRuntime": platform.python_version(),
        "simulationSeed": (
            PIPELINE_SIMULATION_SEED
            if {"scenarios", "playoff_table"} & (previous_tasks | set(task_ids))
            else None
        ),
        "complete": group == "full" or bool(previous and previous.get("complete")),
        "groups": sorted(previous_groups | {group}),
        "taskIds": sorted(previous_tasks | set(task_ids)),
        "artifacts": dict(sorted(artifacts.items())),
    }
    encoded = json.dumps(manifest, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    output_root.mkdir(parents=True, exist_ok=True)
    (output_root / "build_manifest.json").write_text(encoded, encoding="utf-8")
    (workspace / "docs" / "data" / "build_manifest.json").write_text(encoded, encoding="utf-8")
    return manifest


def publish_staged_changes(
    workspace: Path,
    repository_root: Path,
    temporary_root: Path,
    group: str,
    *,
    replace_func=None,
) -> list[str]:
    """Publish manifest-owned files transactionally, rolling back on error.

    Obsolete files are removed only when a complete same-snapshot manifest
    previously owned them. Across snapshots, old generated paths are retained
    because they may be historical links or results.
    """
    manifest = _read_build_manifest(workspace)
    if not manifest or manifest.get("schemaVersion") != 2 or manifest.get("complete") is not True:
        raise ValueError("Cannot publish without a complete artifact-ownership manifest")
    artifacts = manifest.get("artifacts", {})
    candidates: set[Path] = set()
    for relative, digest in artifacts.items():
        rel_path = Path(relative)
        if not is_owned_artifact(relative) or rel_path.is_absolute() or ".." in rel_path.parts:
            raise ValueError(f"Manifest contains an unowned or unsafe artifact: {relative}")
        source = workspace / rel_path
        if not source.is_file() or _sha256(source) != digest:
            raise ValueError(f"Manifest-owned staged artifact is missing or changed: {relative}")
        candidates.add(rel_path)
    candidates.update({Path("output/build_manifest.json"), Path("docs/data/build_manifest.json")})

    previous = _read_build_manifest(repository_root)
    obsolete: set[Path] = set()
    if (previous and previous.get("schemaVersion") == 2 and previous.get("complete") is True
            and previous.get("snapshotId") == manifest.get("snapshotId")):
        for relative in set(previous.get("artifacts", {})) - set(artifacts):
            if is_owned_artifact(relative):
                obsolete.add(Path(relative))

    if (workspace / "index.html").is_file():
        candidates.add(Path("index.html"))

    backups: dict[Path, Path | None] = {}
    replaced: list[Path] = []
    replace = replace_func or os.replace
    try:
        for index, relative in enumerate(sorted(candidates | obsolete, key=lambda item: item.as_posix())):
            if "archive" in relative.parts or relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"Refusing to publish a protected path: {relative}")
            target = repository_root / relative
            if target.exists():
                backup = temporary_root / "backup" / str(index)
                backup.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, backup)
                backups[target] = backup
            else:
                backups[target] = None
            if relative in obsolete:
                target.unlink(missing_ok=True)
                replaced.append(target)
                continue
            source = workspace / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            staged_copy = temporary_root / "publish" / str(index)
            staged_copy.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, staged_copy)
            replace(staged_copy, target)
            replaced.append(target)
    except Exception:
        for target in reversed(replaced):
            backup = backups[target]
            if backup is None:
                target.unlink(missing_ok=True)
            else:
                rollback = temporary_root / "rollback" / str(len(replaced))
                rollback.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(backup, rollback)
                replace(rollback, target)
        raise
    published = candidates | obsolete
    return [path.as_posix() for path in sorted(published, key=lambda item: item.as_posix())]


def _resolve(selected: tuple[str, ...]) -> list[str]:
    ordered: list[str] = []
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(task_id: str) -> None:
        if task_id in visited or task_id == "inputs":
            return
        if task_id not in TASKS:
            raise ValueError(f"Unknown pipeline task or dependency: {task_id}")
        if task_id in visiting:
            raise ValueError(f"Pipeline dependency cycle includes {task_id}")
        visiting.add(task_id)
        for dependency in TASKS[task_id].dependencies:
            visit(dependency)
        visiting.remove(task_id)
        visited.add(task_id)
        ordered.append(task_id)

    for task_id in selected:
        visit(task_id)
    return ordered


def run_pipeline(
    group: str,
    season_index: int = 0,
    *,
    executor: Callable[..., ScriptResult] = run_command,
    staged: bool = True,
    publish: bool = True,
) -> list[ScriptResult]:
    """Run one selection in an isolated workspace and publish only a valid build."""
    if group not in GROUPS:
        raise ValueError(f"Unknown pipeline group: {group}")
    if season_index < 0:
        raise ValueError("CSV season index must be zero or greater")

    repository_root = Path(__file__).resolve().parent.parent
    os.chdir(repository_root)
    results: list[ScriptResult] = []
    required_inputs = {
        "stats": ("MEGA_teams.csv", "MEGA_passing.csv", "MEGA_rushing.csv", "MEGA_receiving.csv", "MEGA_defense.csv", "MEGA_punting.csv", "MEGA_kicking.csv", "MEGA_rankings.csv"),
        "playoff": ("MEGA_teams.csv", "MEGA_games.csv", "MEGA_rankings.csv", "mega_elo.csv"),
        "full": ("MEGA_teams.csv", "MEGA_games.csv", "MEGA_rankings.csv", "mega_elo.csv", "MEGA_users.csv", "MEGA_passing.csv", "MEGA_rushing.csv", "MEGA_receiving.csv", "MEGA_defense.csv", "MEGA_punting.csv", "MEGA_kicking.csv"),
    }[group]
    missing_inputs = [name for name in required_inputs if not (repository_root / name).is_file()]
    if missing_inputs:
        print("Missing required current-cycle inputs: " + ", ".join(missing_inputs))
        return [ScriptResult(ScriptStatus.FAILED, "Input preflight", error="missing: " + ", ".join(missing_inputs))]
    task_ids = _resolve(GROUPS[group])

    metadata_path = repository_root / "docs" / "data" / "import_metadata.json"
    try:
        context = CycleContext.from_file(metadata_path, repository_root)
    except (OSError, ValueError) as exc:
        return [ScriptResult(ScriptStatus.FAILED, "Cycle metadata preflight", error=str(exc))]
    if context.csv_season_index != season_index:
        return [ScriptResult(
            ScriptStatus.FAILED, "Cycle metadata preflight",
            error=f"requested seasonIndex={season_index} does not match active snapshot seasonIndex={context.csv_season_index}",
        )]

    temporary_root = None
    workspace = repository_root
    protected_before = _protected_hashes(repository_root)
    if staged:
        if group != "full":
            previous = _read_build_manifest(repository_root)
            if not previous or previous.get("complete") is not True:
                return [ScriptResult(ScriptStatus.FAILED, "Build preflight", error="subset build requires a complete prior full-build manifest")]
            if previous.get("schemaVersion") != 2:
                return [ScriptResult(ScriptStatus.FAILED, "Build preflight", error="existing manifest has no explicit artifact ownership; run the full pipeline")]
            if previous.get("snapshotId") != context.snapshot_id:
                return [ScriptResult(ScriptStatus.FAILED, "Build preflight", error="existing artifacts belong to another snapshot; run the full pipeline")]
            for relative, digest in previous.get("artifacts", {}).items():
                if not is_owned_artifact(relative) or Path(relative).is_absolute() or ".." in Path(relative).parts:
                    return [ScriptResult(ScriptStatus.FAILED, "Build preflight", error=f"manifest contains an unowned or unsafe artifact: {relative}")]
                path = repository_root / relative
                if not path.is_file() or _sha256(path) != digest:
                    return [ScriptResult(ScriptStatus.FAILED, "Build preflight", error=f"manifest-owned artifact changed or is missing: {relative}")]
        try:
            temporary_root, workspace, protected_before = create_staging_workspace(repository_root)
            if group != "full":
                previous = _read_build_manifest(repository_root) or {}
                for relative in previous.get("artifacts", {}):
                    if task_regenerates_path(relative, task_ids, context.display_season):
                        continue
                    source = repository_root / relative
                    target = workspace / relative
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, target)
        except Exception as exc:
            if temporary_root:
                shutil.rmtree(temporary_root, ignore_errors=True)
            return [ScriptResult(ScriptStatus.FAILED, "Staging preflight", error=str(exc))]

    if staged:
        def staged_executor(script, description, optional=False, extra_args=None):
            return run_command(script, description, optional, extra_args, working_directory=workspace)
        task_executor = staged_executor
    else:
        task_executor = executor

    stopped = False
    index_deferred = False
    try:
        for task_id in task_ids:
            task = TASKS[task_id]
            if stopped:
                results.append(ScriptResult(ScriptStatus.SKIPPED, task.description, error="pipeline stopped after an earlier failure"))
                continue
            if staged and task_id == "index":
                index_deferred = True
                continue
            if task.action == "publish":
                try:
                    publish_browser_data(season_index, root=workspace)
                    missing = task_missing_outputs(workspace, task_id, context.display_season)
                    if missing:
                        raise ValueError("Producer did not create required browser outputs: " + ", ".join(missing))
                    results.append(ScriptResult(ScriptStatus.SUCCEEDED, task.description, 0))
                    print(f"✓ {task.description} completed successfully")
                except Exception as exc:
                    results.append(ScriptResult(ScriptStatus.FAILED, task.description, error=str(exc)))
                    print(f"✗ {task.description} failed: {exc}")
                    stopped = True
                continue

            arguments = task_arguments(task_id, season_index, context)

            result = task_executor(task.script, task.description, task.optional, arguments or None)
            if staged:
                result = validate_task_result(result, workspace, task_id, context.display_season)
            results.append(result)
            if result.status == ScriptStatus.FAILED:
                stopped = True

        if stopped:
            return results
        if not staged:
            return results

        write_build_manifest(workspace, repository_root, group, context, task_ids, include_index=False)
        results.append(ScriptResult(ScriptStatus.SUCCEEDED, "Snapshot manifest", 0))
        if index_deferred:
            index_result = task_executor("scripts/generate_index.py", "Navigation page generation", False, None)
            index_result = validate_task_result(index_result, workspace, "index", context.display_season)
            results.append(index_result)
            if index_result.status == ScriptStatus.FAILED:
                return results
            write_build_manifest(workspace, repository_root, group, context, task_ids, include_index=True)

        if protected_before != _protected_hashes(workspace):
            raise ValueError("Protected formula/model files changed during the staged build")
        if not publish:
            results.append(ScriptResult(ScriptStatus.SUCCEEDED, "Staged build validation (not published)", 0))
            return results
        published = publish_staged_changes(workspace, repository_root, temporary_root, group)
        results.append(ScriptResult(ScriptStatus.SUCCEEDED, f"Published {len(published)} staged files", 0))
    except Exception as exc:
        results.append(ScriptResult(ScriptStatus.FAILED, "Staged build publication", error=str(exc)))
    finally:
        if temporary_root:
            shutil.rmtree(temporary_root, ignore_errors=True)

    print("\nPipeline summary")
    for result in results:
        if result.status == ScriptStatus.SUCCEEDED:
            status = "✓"
        elif result.status == ScriptStatus.SKIPPED:
            status = "↷"
        else:
            status = "✗"
        detail = f" ({result.error})" if result.error else ""
        print(f"{status} {result.description}{detail}")
    return results


def pipeline_succeeded(results: list[ScriptResult]) -> bool:
    return all(result.status != ScriptStatus.FAILED for result in results)
